export function localizeRuntimeError(language: Language, message: string): string {
  if (language !== 'en') return message;
  const ffmpegExit = message.match(/^FFmpegが終了コード(.+)で停止しました。$/);
  if (ffmpegExit) return `FFmpeg stopped with exit code ${ffmpegExit[1]}.`;
  const translation = japaneseToEnglishErrors.find(([japanese]) => message.startsWith(japanese));
  if (!translation) return message;
  const [japanese, english] = translation;
  return `${english}${message.slice(japanese.length)}`;
}
