import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(repositoryRoot, 'shared', 'app-error-codes.json');
const typescriptPath = resolve(repositoryRoot, 'src', 'lib', 'app-error-codes.generated.ts');
const rustPath = resolve(repositoryRoot, 'src-tauri', 'src', 'app_error_codes.generated.rs');
const checkOnly = process.argv.includes('--check');

const source = JSON.parse(await readFile(sourcePath, 'utf8'));
const codes = source.codes;
if (!Array.isArray(codes) || codes.length === 0 || !codes.every(isValidCode)) {
  throw new Error('shared/app-error-codes.json codes must contain unique snake_case strings.');
}
if (new Set(codes).size !== codes.length) {
  throw new Error('shared/app-error-codes.json contains duplicate codes.');
}

const typescript = `// Generated by scripts/generate-error-contract.mjs. Do not edit directly.\nexport const appErrorCodes = ${JSON.stringify(codes, null, 2)} as const;\n\nexport type AppErrorCode = (typeof appErrorCodes)[number];\n`;
const variants = codes
  .map((code) => {
    const variant = code
      .split('_')
      .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
      .join('');
    const cfg = source.rustCfg?.[code];
    if (cfg !== undefined && cfg !== 'not(windows)') {
      throw new Error(`Unsupported Rust cfg for ${code}: ${cfg}`);
    }
    const cfgAttribute = cfg ? `    #[cfg(${cfg})]\n` : '';
    return `${cfgAttribute}    #[serde(rename = "${code}")]\n    ${variant},`;
  })
  .join('\n');
const rust = `// Generated by scripts/generate-error-contract.mjs. Do not edit directly.\n#[derive(Debug, Clone, Copy, Serialize, PartialEq, Eq)]\npub enum ErrorCode {\n${variants}\n}\n`;

await updateGeneratedFile(typescriptPath, typescript);
await updateGeneratedFile(rustPath, rust);

function isValidCode(value) {
  return typeof value === 'string' && /^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$/.test(value);
}

async function updateGeneratedFile(path, expected) {
  if (!checkOnly) {
    await writeFile(path, expected, 'utf8');
    return;
  }
  const current = await readFile(path, 'utf8').catch(() => '');
  if (current !== expected) {
    throw new Error(`${path} is stale. Run npm run generate:contracts.`);
  }
}
